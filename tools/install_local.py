#!/usr/bin/python3
"""Install the source checkout as a user service and an application-menu entry."""
import argparse
import os
from pathlib import Path
import subprocess
import sys

ROOT=Path(__file__).resolve().parents[1]
MARKER='# Generated by ClipDeck local installer.'

def unit_quote(value):
    return '"'+str(value).replace('\\','\\\\').replace('"','\\"').replace('%','%%')+'"'

def desktop_quote(value):
    return '"'+str(value).replace('\\','\\\\').replace('"','\\"').replace('`','\\`').replace('$','\\$').replace('%','%%')+'"'

def write_owned(path,text):
    if path.exists() and MARKER not in path.read_text():
        raise RuntimeError(f'Refusing to replace an unrelated file: {path}')
    path.parent.mkdir(parents=True,exist_ok=True)
    path.write_text(MARKER+'\n'+text)
    path.chmod(0o644)

def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--data-dir',type=Path)
    parser.add_argument('--x11',action='store_true',help='Use X11/XWayland for capture without the GNOME companion')
    args=parser.parse_args()
    config=Path(os.environ.get('XDG_CONFIG_HOME',Path.home()/'.config'))
    data=Path(os.environ.get('XDG_DATA_HOME',Path.home()/'.local/share'))
    unit=config/'systemd/user/clipdeck-local.service'
    environment='Environment=CLIPDECK_SERVICE=clipdeck-local.service\n'
    if args.data_dir:
        environment+='Environment='+unit_quote('CLIPDECK_DATA_DIR='+str(args.data_dir.resolve()))+'\n'
    if args.x11: environment+='Environment=GDK_BACKEND=x11\n'
    write_owned(unit,f'''[Unit]
Description=ClipDeck local background clipboard service
After=graphical-session.target
PartOf=graphical-session.target

[Service]
Type=dbus
BusName=io.github.clipdeck.ClipDeck
ExecStart=/usr/bin/python3 {unit_quote(ROOT/'run.py')} --background
Restart=on-failure
RestartSec=2
TimeoutStopSec=5
{environment}
[Install]
WantedBy=graphical-session.target
''')
    desktop=data/'applications/io.github.clipdeck.Local.desktop'
    write_owned(desktop,f'''[Desktop Entry]
Type=Application
Name=ClipDeck (Local)
Comment=Open the full ClipDeck application
Exec=/usr/bin/python3 {desktop_quote(ROOT/'launcher.py')} --full
Icon={ROOT/'data/io.github.clipdeck.ClipDeck.svg'}
Terminal=false
Categories=Utility;GTK;
StartupNotify=true
StartupWMClass=io.github.clipdeck.ClipDeck
''')
    sys.path.insert(0,str(ROOT))
    from clipdeck.desktop import start_service
    if not start_service('clipdeck-local.service', restart=True, reload=True):
        raise RuntimeError('ClipDeck service did not become active')
    print('Started clipdeck-local.service; app icon: ClipDeck (Local)')
    print('Super+V is configured by the background process.')

if __name__=='__main__': main()
